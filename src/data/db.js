// ── Expense Templates ─────────────────────────────────────────────────────────
export const expenseTemplates = {
  getAll: async () => {
    const { data } = await supabase.from('expense_templates').select('*')
      .eq('store_id', sid()).order('created_at')
    return (data ?? []).map(fromDbTemplate)
  },

  create: async (template) => {
    const item = {
      ...template,
      id: uid(), isTemplate: true, active: true,
      lastImputedMonth: null, createdAt: new Date().toISOString(),
    }
    const { error } = await supabase.from('expense_templates').insert(toDbTemplate(item, sid()))
    if (error) throw error
    return item
  },

  update: async (id, updates) => {
    const map = {
      description: 'description', amount: 'amount', docType: 'doc_type',
      active: 'active', lastImputedMonth: 'last_imputed_month',
    }
    const dbUpdates = {}
    for (const [k, dbk] of Object.entries(map)) {
      if (k in updates) dbUpdates[dbk] = updates[k]
    }
    const { data } = await supabase.from('expense_templates').update(dbUpdates)
      .eq('store_id', sid()).eq('id', id).select().maybeSingle()
    return data ? fromDbTemplate(data) : null
  },

  delete: async (id) => {
    await supabase.from('expense_templates').delete().eq('store_id', sid()).eq('id', id)
  },

  // Corrige gastos imputados desde plantilla que quedaron con type='variable' por bug anterior
  fixWrongTypes: async () => {
    const storeId = sid()
    await supabase.from('expenses')
      .update({ type: 'fixed' })
      .eq('store_id', storeId)
      .not('template_id', 'is', null)
      .eq('type', 'variable')
  },

  imputeNow: async (templateId, date) => {
    const storeId = sid()
    const { data } = await supabase.from('expense_templates').select('*')
      .eq('store_id', storeId).eq('id', templateId).maybeSingle()
    if (!data) return null

    const t = fromDbTemplate(data)
    const useDate = date ?? new Date().toISOString().split('T')[0]
    const month = useDate.slice(0, 7)
    const ivaCredito = t.docType === 'factura' ? t.amount - t.amount / 1.19 : 0

    const tx = await _insertExpense({
      ...t, isTemplate: false, templateId: t.id, type: 'fixed',
      date: useDate, autoGenerated: false, ivaCredito,
    })
    await supabase.from('expense_templates')
      .update({ last_imputed_month: month }).eq('store_id', storeId).eq('id', templateId)
    return tx
  },

  autoImputeMonth: async () => {
    const storeId = sid()
    const month = nowMonth()
    const { data: templates } = await supabase.from('expense_templates').select('*')
      .eq('store_id', storeId).eq('active', true)
    if (!templates?.length) return []

    const imputados = []
    for (const row of templates) {
      if (row.last_imputed_month === month) continue
      const t = fromDbTemplate(row)
      const ivaCredito = t.docType === 'factura' ? t.amount - t.amount / 1.19 : 0

      await _insertExpense({
        ...t, isTemplate: false, templateId: t.id, type: 'fixed',
        date: `${month}-01`, autoGenerated: true, ivaCredito,
      })
      await supabase.from('expense_templates')
        .update({ last_imputed_month: month }).eq('store_id', storeId).eq('id', row.id)
      imputados.push(t.description)
    }
    return imputados
  },
}

