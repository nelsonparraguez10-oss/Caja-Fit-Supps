// Persistencia sobre Supabase — reemplaza la versión localStorage
import { supabase, getStoreId } from '../lib/supabase'

const uid = () => Date.now().toString(36) + Math.random().toString(36).slice(2)

// Retorna el store_id del usuario autenticado (cacheado en módulo)
function sid() {
  const id = getStoreId()
  if (!id) throw new Error('Sin sesión activa')
  return id
}

const nowMonth = () => {
  const d = new Date()
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`
}

// ── Mappers: DB (snake_case) ↔ JS (camelCase) ────────────────────────────────

function fromDbProduct(r) {
  return {
    id:        r.id,        barcode:   r.barcode,
    name:      r.name,      variante:  r.variante,
    marca:     r.marca,     proveedor: r.proveedor,
    category:  r.category,
    price:     Number(r.price),
    cost:      Number(r.cost),
    stock:     Number(r.stock),
    margenPct: r.margen_pct !== null ? Number(r.margen_pct) : null,
    createdAt: r.created_at,
  }
}
function toDbProduct(p, storeId) {
  return {
    id: p.id, store_id: storeId, barcode: p.barcode, name: p.name,
    variante: p.variante ?? null, marca: p.marca ?? null,
    proveedor: p.proveedor ?? null, category: p.category ?? null,
    price: p.price ?? 0, cost: p.cost ?? 0, stock: p.stock ?? 0,
    margen_pct: p.margenPct ?? null, created_at: p.createdAt,
  }
}

function fromDbSale(r) {
  return {
    id:             r.id,
    date:           r.date,
    channel:        r.channel,
    items:          r.items,
    listTotal:      Number(r.list_total),
    discount:       Number(r.discount),
    discountAmount: Number(r.discount_amount),
    effectiveTotal: Number(r.effective_total),
    total:          Number(r.effective_total),
    paymentMethod:  r.payment_method,
    cardCommission: Number(r.card_commission),
    shipping:       r.shipping,
    status:         r.status,
    voidedAt:       r.voided_at,
  }
}
function toDbSale(s, storeId) {
  const eff = s.effectiveTotal ?? s.listTotal ?? s.total ?? 0
  return {
    id: s.id, store_id: storeId,
    date:            s.date            ?? new Date().toISOString(),
    channel:         s.channel         ?? 'POS',
    items:           s.items           ?? [],
    list_total:      s.listTotal       ?? eff,
    discount:        s.discount        ?? 0,
    discount_amount: s.discountAmount  ?? 0,
    effective_total: eff,
    payment_method:  s.paymentMethod   ?? null,
    card_commission: s.cardCommission  ?? 0,
    shipping:        s.shipping        ?? { cobro: 0, costo: 0, margin: 0 },
    status:          s.status          ?? 'COMPLETED',
    voided_at:       s.voidedAt        ?? null,
  }
}

