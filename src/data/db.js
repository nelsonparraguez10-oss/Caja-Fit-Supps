// ── Products ──────────────────────────────────────────────────────────────────
export const products = {
  getAll: async () => {
    const { data } = await supabase.from('products').select('*')
      .eq('store_id', sid()).order('name')
    return (data ?? []).map(fromDbProduct)
  },

  findByBarcode: async (barcode) => {
    const { data } = await supabase.from('products').select('*')
      .eq('store_id', sid()).eq('barcode', barcode).maybeSingle()
    return data ? fromDbProduct(data) : null
  },

  create: async (product) => {
    const item = { ...product, id: uid(), createdAt: new Date().toISOString() }
    const { error } = await supabase.from('products').insert(toDbProduct(item, sid()))
    if (error) throw error
    return item
  },

  update: async (barcode, updates) => {
    const map = {
      name: 'name', variante: 'variante', marca: 'marca',
      proveedor: 'proveedor', category: 'category',
      price: 'price', cost: 'cost', stock: 'stock', margenPct: 'margen_pct',
    }
    const dbUpdates = {}
    for (const [k, dbk] of Object.entries(map)) {
      if (k in updates) dbUpdates[dbk] = updates[k]
    }
    const { data } = await supabase.from('products').update(dbUpdates)
      .eq('store_id', sid()).eq('barcode', barcode).select().maybeSingle()
    return data ? fromDbProduct(data) : null
  },

  delete: async (barcode) => {
    await supabase.from('products').delete().eq('store_id', sid()).eq('barcode', barcode)
  },

  decrementStock: async (barcode, qty) => {
    await supabase.rpc('decrement_stock', { p_store_id: sid(), p_barcode: barcode, p_qty: qty })
  },

}

// ── Sales ─────────────────────────────────────────────────────────────────────
export const sales = {
  getAll: async () => {
    const { data } = await supabase.from('sales').select('*')
      .eq('store_id', sid()).order('date', { ascending: false })
    return (data ?? []).map(fromDbSale)
      .sort((a, b) => new Date(b.date) - new Date(a.date))
  },

  create: async (sale) => {
    const effectiveTotal = sale.effectiveTotal ?? sale.listTotal ?? sale.total ?? 0
    const item = { ...sale, id: uid(), date: new Date().toISOString(), effectiveTotal, total: effectiveTotal }
    const { error } = await supabase.from('sales').insert(toDbSale(item, sid()))
    if (error) throw error
    await Promise.all(item.items.map((i) => products.decrementStock(i.barcode, i.quantity)))
    return item
  },

  delete: async (id) => {
    await supabase.from('sales').delete().eq('store_id', sid()).eq('id', id)
  },

  voidSale: async (id) => {
    const storeId = sid()
    const { data: sale } = await supabase.from('sales').select('*')
      .eq('store_id', storeId).eq('id', id).maybeSingle()
    if (!sale || sale.status === 'VOIDED') return null

    // Devolver stock de forma paralela y atómica
    await Promise.all(
      (sale.items ?? []).map((i) =>
        supabase.rpc('increment_stock', { p_store_id: storeId, p_barcode: i.barcode, p_qty: i.quantity }),
      ),
    )
    await supabase.from('sales').update({ status: 'VOIDED', voided_at: new Date().toISOString() })
      .eq('store_id', storeId).eq('id', id)
  },
}

